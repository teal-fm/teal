// Learn more https://docs.expo.io/guides/customizing-metro
const { getDefaultConfig } = require("expo/metro-config");
const { FileStore } = require("metro-cache");
const path = require("path");
const { withNativewind } = require("nativewind/metro");

const {
  wrapWithReanimatedMetroConfig,
} = require("react-native-reanimated/metro-config");

// Expo caches compiled CSS by the stylesheet's own content, and Tailwind's scan of
// the source files is not part of that key, so class names added after Metro starts
// never reach the dev stylesheet. The app imports global.entry.css (generated,
// gitignored); in development it is rewritten whenever app code changes, which
// changes its content and makes Metro recompile it and Tailwind rescan.
const fs = require("fs");
const cssEntry = path.join(__dirname, "global.entry.css");
let entryStamp = 0;
function writeCssEntry() {
  entryStamp += 1;
  fs.writeFileSync(
    cssEntry,
    `@import "./global.css";\n/* generated by metro.config.js: ${entryStamp} */\n`,
  );
}
writeCssEntry();
if (process.env.NODE_ENV !== "production" && !process.env.CI) {
  let pending;
  for (const dir of ["app", "components", "lib", "next"]) {
    try {
      fs.watch(path.join(__dirname, dir), { recursive: true }, (_event, file) => {
        if (!file || !/\.(tsx?|jsx?)$/.test(file)) return;
        clearTimeout(pending);
        pending = setTimeout(writeCssEntry, 150);
      });
    } catch {
      // Recursive watching is unavailable on some platforms; restart Metro to pick up new classes.
    }
  }
  // Token edits in global.css need the same nudge, or Expo keeps serving the old file.
  fs.watch(path.join(__dirname, "global.css"), () => {
    clearTimeout(pending);
    pending = setTimeout(writeCssEntry, 150);
  });
}

/** @type {import('expo/metro-config').MetroConfig} */
const config = getDefaultConfig(__dirname);
const defaultResolveRequest = config.resolver.resolveRequest;

config.resolver.resolveRequest = (context, moduleName, platform) => {
  if (
    moduleName === "./expo-oauth-client.js" &&
    context.originModulePath.includes("@atproto/oauth-client-expo")
  ) {
    return context.resolveRequest(context, "./expo-oauth-client", platform);
  }

  return defaultResolveRequest
    ? defaultResolveRequest(context, moduleName, platform)
    : context.resolveRequest(context, moduleName, platform);
};

config.cacheStores = [
  new FileStore({
    root: path.join(__dirname, "node_modules", ".cache", "metro"),
  }),
];

module.exports = wrapWithReanimatedMetroConfig(
  withNativewind(config),
);
